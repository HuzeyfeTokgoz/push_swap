#include "libft.h"

size_t	ft_strlcat(char *dst, const char *src, size_t size)
{
	size_t	i;
	size_t	d_len;
	size_t	s_len;

	s_len = ft_strlen((char *)src);
	if (!dst && size == 0)
		return (s_len);
	d_len = ft_strlen(dst);
	i = 0;
	if (size <= d_len)
		return (size + s_len);
	while (src[i] && d_len + i < size - 1)
	{
		dst[d_len + i] = src[i];
		i++;
	}
	dst[d_len + i] = '\0';
	return (d_len + s_len);
}
